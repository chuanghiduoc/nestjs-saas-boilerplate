import { kyselyAdapter } from '@better-auth/kysely-adapter';
import { betterAuth, type BetterAuthOptions } from 'better-auth';
import { createAuthMiddleware } from 'better-auth/api';
import { CamelCasePlugin, Kysely, PostgresDialect } from 'kysely';
import pg from 'pg';
import { v7, version } from 'uuid';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { databaseConfig } from '../../../src/core/database/index.js';
import {
  authDatabaseConfig,
  identityConfig,
  identityGuardConfig,
} from '../../../src/modules/identity/identity.config.js';
import { buildAuthOptions } from '../../../src/modules/identity/infra/better-auth/auth-options.js';
import { createAuthPool } from '../../../src/modules/identity/infra/better-auth/auth-pool.js';
import { applyTestEnv } from '../../support/app-factory.js';

const PASSWORD = 'correct-horse-battery-staple';
const noop = createAuthMiddleware(async () => undefined);

/** Better Auth thật (options từ `buildAuthOptions`) trên pool `auth_user` + Kysely adapter như production. */
describe('buildAuthOptions driving a real Better Auth on Postgres', () => {
  let pool: pg.Pool;
  let db: Kysely<Record<string, never>>;
  const emails: string[] = [];
  /** Tại thời điểm callback chạy, user đã commit (thấy được từ connection khác) hay chưa. */
  const committedAtSend: boolean[] = [];

  const makeAuth = (env: Record<string, string>, corsOrigins: string[]) =>
    betterAuth(
      buildAuthOptions({
        identity: identityConfig.schema.parse({
          secret: 's'.repeat(40),
          ...env,
        }),
        // Rate limit không phải đối tượng test ở đây; bật thì các lần chạy lặp lại trên cùng DB sẽ bị chặn.
        guard: identityGuardConfig.schema.parse({ rateLimitEnabled: 'false' }),
        app: { serviceName: 'svc' },
        corsOrigins,
        database: (o: BetterAuthOptions) =>
          kyselyAdapter(db, { type: 'postgres', transaction: true })(o),
        hooks: { before: noop, after: noop },
        emails: {
          verification: async ({ user }) => {
            const seen = await pool.query(
              'SELECT 1 FROM "user" WHERE email = $1',
              [user.email],
            );
            committedAtSend.push(seen.rowCount === 1);
          },
          reset: async () => undefined,
          existingAccount: async () => undefined,
          changeEmailConfirmation: async () => undefined,
        },
        onUserCreated: async () => undefined,
        onApiError: () => undefined,
        log: () => undefined,
      }),
    );

  const post = (
    auth: ReturnType<typeof makeAuth>,
    base: string,
    path: string,
    body: unknown,
  ) =>
    auth.handler(
      new Request(`${base}/api/auth${path}`, {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify(body),
      }),
    );

  const signUp = async (
    auth: ReturnType<typeof makeAuth>,
    base: string,
  ): Promise<string> => {
    const email = `ao-${v7()}@example.test`;
    emails.push(email);
    const res = await post(auth, base, '/sign-up/email', {
      email,
      password: PASSWORD,
      name: 'A',
    });
    expect(res.status).toBe(200);
    return email;
  };

  /** `Set-Cookie` của session sau khi đăng nhập (cần AUTH_REQUIRE_EMAIL_VERIFICATION=false để đăng nhập ngay). */
  const sessionCookie = async (
    env: Record<string, string>,
    corsOrigins: string[],
  ): Promise<string> => {
    const base = env.baseUrl ?? '';
    const auth = makeAuth(
      { ...env, requireEmailVerification: 'false' },
      corsOrigins,
    );
    const email = await signUp(auth, base);
    const res = await post(auth, base, '/sign-in/email', {
      email,
      password: PASSWORD,
    });
    expect(res.status).toBe(200);
    const cookie = res.headers
      .getSetCookie()
      .find((c) => c.includes('session_token='));
    if (!cookie) throw new Error('no session cookie was set');
    return cookie;
  };

  beforeAll(() => {
    applyTestEnv();
    pool = createAuthPool(authDatabaseConfig(), databaseConfig());
    db = new Kysely({
      dialect: new PostgresDialect({ pool }),
      plugins: [new CamelCasePlugin()],
    });
  });
  afterAll(async () => {
    if (pool && emails.length)
      await pool.query('DELETE FROM "user" WHERE email = ANY($1)', [emails]);
    await db?.destroy();
  });

  it('S2-R41: ids of user, account and session are UUIDv7 generated by the database', async () => {
    const base = 'http://localhost:3000';
    const auth = makeAuth(
      {
        baseUrl: base,
        secureCookies: 'false',
        requireEmailVerification: 'false',
      },
      [],
    );
    const email = await signUp(auth, base);
    const signIn = await post(auth, base, '/sign-in/email', {
      email,
      password: PASSWORD,
    });
    expect(signIn.status).toBe(200);
    const { rows } = await pool.query<{ u: string; a: string; s: string }>(
      `SELECT u.id AS u, a.id AS a, s.id AS s FROM "user" u
        JOIN account a ON a.user_id = u.id JOIN session s ON s.user_id = u.id WHERE u.email = $1`,
      [email],
    );
    expect(rows).toHaveLength(1);
    const row = rows[0];
    if (!row) throw new Error('user row missing');
    expect([row.u, row.a, row.s].map((id) => version(id))).toEqual([7, 7, 7]);
  });

  it('M7: the verification email is requested only after the sign-up transaction committed', async () => {
    const base = 'http://localhost:3000';
    const auth = makeAuth({ baseUrl: base, secureCookies: 'false' }, []);
    committedAtSend.length = 0;
    await signUp(auth, base);
    expect(committedAtSend).toEqual([true]);
  });

  it('M6: production-like cookie is __Secure-, Secure, HttpOnly, SameSite and Domain from config', async () => {
    const cookie = await sessionCookie(
      {
        baseUrl: 'https://api.example.test',
        cookieSameSite: 'strict',
        cookieDomain: 'example.test',
        cookieDomainAllSubdomainsTrusted: 'true',
      },
      ['https://app.example.test'],
    );
    expect(cookie).toMatch(/^__Secure-svc\.session_token=/);
    const attrs = cookie.toLowerCase().split('; ');
    expect(attrs).toEqual(
      expect.arrayContaining([
        'secure',
        'httponly',
        'samesite=strict',
        'path=/',
        'domain=example.test',
      ]),
    );
  });

  it('M6: dev cookie on http://localhost has no Secure, no __Secure- prefix and no Domain', async () => {
    const cookie = await sessionCookie(
      { baseUrl: 'http://localhost:3000', secureCookies: 'false' },
      [],
    );
    expect(cookie).toMatch(/^svc\.session_token=/);
    const attrs = cookie.toLowerCase().split('; ');
    expect(attrs).toEqual(
      expect.arrayContaining(['httponly', 'samesite=lax', 'path=/']),
    );
    expect(attrs).not.toContain('secure');
    expect(attrs.some((a) => a.startsWith('domain='))).toBe(false);
  });
});
